import assert from 'node:assert/strict';
import fs from 'node:fs';
import ts from 'typescript';

async function load(file) {
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
  return import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
}
const { cmsEnabled, cmsEnvironment } = await load('cms/environment.ts');
assert.equal(cmsEnabled({}), false);
assert.equal(cmsEnabled({ CMS_ENABLED: 'false' }), false);
assert.equal(cmsEnvironment({}).enabled, false);
assert.throws(() => cmsEnvironment({ CMS_ENABLED: 'true' }), /PAYLOAD_SECRET/);
const env = { CMS_ENABLED: 'true', PAYLOAD_SECRET: 'x'.repeat(40), DATABASE_URL: 'postgres://local/test', S3_BUCKET: 'test', S3_REGION: 'us-east-1', S3_ACCESS_KEY_ID: 'test', S3_SECRET_ACCESS_KEY: 'test', CMS_SERVER_URL: 'http://localhost:3000' };
assert.equal(cmsEnvironment(env).enabled, true);
assert.throws(() => cmsEnvironment({ ...env, PAYLOAD_SECRET: 'short' }), /32/);
assert.throws(() => cmsEnvironment({ ...env, DATABASE_URL: 'sqlite:test' }), /PostgreSQL/);
assert.equal(cmsEnvironment({ ...env, NODE_ENV: 'production' }).enabled, true);
assert.throws(() => cmsEnvironment({ ...env, NODE_ENV: 'production', CMS_SERVER_URL: 'http://example.com' }), /HTTPS/);
const { adminOnly, editorialUser, publishedOnly, ownUserOrAdmin } = await load('cms/access.ts');
const request = (user) => ({ req: { user } });
assert.equal(adminOnly(request(null)), false);
assert.equal(adminOnly(request({ collection: 'legacy', role: 'admin' })), false);
assert.equal(adminOnly(request({ collection: 'users', role: 'writer' })), false);
assert.equal(adminOnly(request({ collection: 'users', role: 'admin' })), true);
assert.equal(editorialUser(request({ collection: 'users', role: 'editor' })), true);
assert.equal(adminOnly(request({ collection: 'users', role: 'editor' })), false);
assert.deepEqual(publishedOnly(request(null)), { _status: { equals: 'published' } });
const { contentSource } = await load('lib/content-source.ts');
delete process.env.CONTENT_SOURCE;
assert.equal(contentSource(), 'demo');
process.env.CONTENT_SOURCE = 'payload'; assert.equal(contentSource(), 'payload');
process.env.CONTENT_SOURCE = 'invalid'; assert.throws(contentSource);
delete process.env.CONTENT_SOURCE;
assert.equal(ownUserOrAdmin(request(null)), false);
assert.deepEqual(ownUserOrAdmin(request({ id: 3, collection: 'users', role: 'writer' })), { id: { equals: 3 } });
const access = await load('cms/access.ts');
const lena = request({ id: 7, collection: 'users', role: 'municipal', municipalSpace: 2 });
const orphan = request({ id: 8, collection: 'users', role: 'municipal', municipalSpace: null });
assert.equal(access.municipalUser(lena), true);
assert.equal(access.municipalUser(orphan), false);
assert.equal(access.editorialUser(lena), false);
assert.equal(access.adminOnly(lena), false);
assert.equal(access.municipalSpaceOf({ user: { collection: 'users', role: 'municipal', municipalSpace: { id: 2 } } }), 2);
assert.deepEqual(access.municipalContentRead(lena), { or: [{ space: { equals: 2 } }, { _status: { equals: 'published' } }] });
assert.deepEqual(access.municipalContentRead(request(null)), { _status: { equals: 'published' } });
assert.equal(access.municipalContentRead(request({ collection: 'users', role: 'editor' })), true);
assert.deepEqual(access.municipalContentVersions(lena), { 'version.space': { equals: 2 } });
assert.equal(access.municipalContentVersions(request(null)), false);
assert.deepEqual(access.municipalContentUpdate(lena), { space: { equals: 2 } });
assert.equal(access.municipalContentUpdate(orphan), false);
assert.equal(access.municipalContentCreate({ ...lena, data: { space: 2 } }), true);
assert.equal(access.municipalContentCreate({ ...lena, data: { space: 3 } }), false);
assert.equal(access.editorialContentRead(lena), false);
assert.deepEqual(access.editorialContentRead(request(null)), { _status: { equals: 'published' } });
assert.equal(access.notMunicipal(lena), false);
assert.equal(access.notMunicipal(request(null)), true);
console.log('PASS: CMS activation, configuration, HTTPS, anonymous access and role isolation');
